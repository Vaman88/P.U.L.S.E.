import { readFileSync } from 'node:fs'
import { expect, test } from '@playwright/test'

const prototypeUrl = new URL('../../prototype.html', import.meta.url).href
const example = JSON.parse(readFileSync(new URL('../public/illustrative-plan.json', import.meta.url), 'utf8'))
test.use({ channel: 'chrome' })

test('both CSVs unlock one train button and the illustrative results', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(plan => {
    const originalFetch = window.fetch.bind(window)
    window.fetch = (input, init) => String(input).includes('illustrative-plan.json')
      ? Promise.resolve(new Response(JSON.stringify(plan), { status: 200 }))
      : originalFetch(input, init)
  }, example)
  await page.goto(prototypeUrl)
  await page.locator('.nav [data-screen="workspace"]').click()
  await page.locator('#username').fill('preview')
  await page.locator('#password').fill('password123456')
  await page.locator('#access-submit').click()
  await expect(page.locator('#preview-example-plan')).toHaveCount(0)
  await expect(page.locator('#demo')).toHaveCount(0)
  await page.locator('#train-device').click()
  await expect(page.locator('#train-state')).toContainText('Choose both CSV files')
  await expect(page.locator('#train-progress')).toBeHidden()
  await page.locator('#sales-file').setInputFiles({ name: 'sales.csv', mimeType: 'text/csv', buffer: Buffer.from('date,drug_name,units_sold\n2026-10-15,Example,1') })
  await page.locator('#inventory-file').setInputFiles({ name: 'inventory.csv', mimeType: 'text/csv', buffer: Buffer.from('date,drug_name,on_hand_units\n2026-10-15,Example,20') })
  await page.locator('#train-device').click()
  await expect(page.locator('#train-progress')).toBeVisible()
  expect(await page.locator('#train-progress span').evaluate(element => getComputedStyle(element).animationName)).toBe('train-progress')
  await expect(page.locator('#plan')).toHaveClass(/active/)
  await expect(page.locator('#train-progress')).toBeHidden()
  await expect(page.locator('#plan-example-note')).toBeVisible()
  await expect(page.locator('#private-rows tr')).toHaveCount(24)
  await expect(page.locator('#private-rows tr').first()).toContainText('15 bottles')
  await expect(page.locator('#private-suggested')).toContainText('15 bottles')
  await expect(page.locator('#private-next-order')).toContainText('15 bottles')
  const [download] = await Promise.all([page.waitForEvent('download'), page.locator('#private-export').click()])
  const csv = readFileSync(await download.path(), 'utf8')
  expect(csv).toContain('order_packages')
  expect(csv).toContain('Metformin ER 500 mg')
  expect(csv).toContain('"15","bottle","100"')
  await expect(page.locator('#private-stats')).toContainText('Suggested orders to review')
  await expect.poll(() => page.locator('body > canvas').count()).toBeGreaterThan(0)
})
